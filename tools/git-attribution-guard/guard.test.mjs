import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync, mkdirSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { violation } from './guard.mjs';

const guard = join(dirname(fileURLToPath(import.meta.url)), 'guard.mjs');

test('rejects trailers and AI credits but allows ordinary configuration messages', () => {
  for (const message of ['Fix\n\nCo-authored-by: Human <human@example.test>', 'Fix\nco-Authored-By: Copilot',
    'Generated with Claude Code', 'Signed-off-by: GitHub Copilot <bot@example.test>', 'Generated by OpenAI']) assert(violation(message));
  for (const message of ['Fix MCP routing', 'Prevent Copilot attribution in commits', 'Document AI safety checks']) assert.equal(violation(message), null);
});

test('commit/push guard covers non-HEAD commits, new branches, tags, identities and existing hooks', () => {
  const root = mkdtempSync(join(tmpdir(), 'git-attribution-test-'));
  const repository = join(root, 'repository');
  const remote = join(root, 'remote.git');
  const env = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1',
    GIT_AUTHOR_NAME: 'Test User', GIT_AUTHOR_EMAIL: 'test@example.test', GIT_COMMITTER_NAME: 'Test User', GIT_COMMITTER_EMAIL: 'test@example.test' };
  const run = (cwd, args, input, overrides = {}) => spawnSync('git', args, { cwd, env: { ...env, ...overrides }, input, encoding: 'utf8' });
  const git = (...args) => { const result = run(repository, args); assert.equal(result.status, 0, result.stderr); return result.stdout.trim(); };
  const check = (hook, args, input = '', overrides = {}) => spawnSync(process.execPath, [guard, hook, ...args], { cwd: repository, env: { ...env, ...overrides }, input, encoding: 'utf8' });
  const line = (object, ref = 'refs/heads/main') => `${ref} ${object} ${ref} ${'0'.repeat(40)}\n`;
  try {
    assert.equal(run(root, ['init', '-q', repository]).status, 0);
    assert.equal(run(root, ['init', '--bare', '-q', remote]).status, 0);
    const message = join(root, 'message');
    writeFileSync(message, 'Good message\n');
    assert.equal(check('commit-msg', [message]).status, 0);
    writeFileSync(message, 'Fix\n\nCo-authored-by: Copilot <bot@example.test>\n');
    assert.notEqual(check('commit-msg', [message]).status, 0);
    writeFileSync(message, 'Good message\n');
    assert.notEqual(check('commit-msg', [message], '', { GIT_AUTHOR_NAME: 'GitHub Copilot' }).status, 0);
    git('commit', '--allow-empty', '-qm', 'Clean baseline');
    const baseline = git('rev-parse', 'HEAD');
    assert.equal(check('pre-push', ['origin', remote], line(baseline)).status, 0);
    git('push', '-q', remote, 'HEAD:refs/heads/main');
    git('commit', '--allow-empty', '-qm', 'Forbidden\n\nCo-authored-by: Copilot <bot@example.test>');
    const forbidden = git('rev-parse', 'HEAD');
    git('commit', '--allow-empty', '-qm', 'Clean HEAD does not hide an earlier forbidden commit');
    assert.notEqual(check('pre-push', ['origin', remote], line(git('rev-parse', 'HEAD'))).status, 0);
    assert.notEqual(check('pre-push', ['origin', remote], line(forbidden, 'refs/heads/new-branch')).status, 0);
    git('tag', '-a', 'bad-tag', baseline, '-m', 'Generated with Claude Code');
    assert.notEqual(check('pre-push', ['origin', remote], line(git('rev-parse', 'bad-tag'), 'refs/tags/bad-tag')).status, 0);
    assert.equal(check('pre-push', ['origin', remote], line('0'.repeat(40))).status, 0);
    const hooks = join(repository, '.git', 'hooks');
    mkdirSync(hooks, { recursive: true });
    const previous = join(hooks, 'commit-msg');
    writeFileSync(previous, '#!/bin/sh\nprintf "\\nCo-authored-by: Copilot\\n" >> "$1"\n');
    chmodSync(previous, 0o755);
    assert.notEqual(check('commit-msg', [message]).status, 0);
    rmSync(previous);
    const prePush = join(hooks, 'pre-push');
    writeFileSync(prePush, '#!/bin/sh\ngrep -q refs/heads/main || exit 7\n');
    chmodSync(prePush, 0o755);
    assert.equal(check('pre-push', ['origin', remote], line(baseline)).status, 0);
    assert.notEqual(check('pre-push', ['origin', remote], line(baseline, 'refs/heads/other')).status, 0);
    rmSync(prePush);
    const activeHooks = join(root, 'active-hooks');
    mkdirSync(activeHooks);
    for (const hook of ['commit-msg', 'pre-push']) {
      const path = join(activeHooks, hook);
      writeFileSync(path, `#!/bin/sh\nexec '${process.execPath}' '${guard}' '${hook}' "$@"\n`);
      chmodSync(path, 0o755);
    }
    git('config', 'core.hooksPath', activeHooks);
    assert.notEqual(run(repository, ['commit', '--allow-empty', '-qm', 'Bad\n\nCo-authored-by: Copilot']).status, 0);
    git('commit', '--allow-empty', '-qm', 'Good message with real commit hook');
    assert.notEqual(run(repository, ['push', remote, 'HEAD:refs/heads/blocked']).status, 0);
    assert.notEqual(run(repository, ['push', remote, 'refs/tags/bad-tag']).status, 0);
    git('push', '-q', remote, `${baseline}:refs/heads/clean`);
  } finally { rmSync(root, { recursive: true, force: true }); }
});